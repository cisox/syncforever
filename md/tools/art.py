"""The Genesis app's own art, drawn from its font at build time (no one else's artwork).

Writes OUT_BIN (4bpp tiles, 32 bytes each) and OUT_H (their numbers, relative to ART_TILE):
- the title, "SYNC FOREVER" drawn 2x: 4 tiles per letter (spaces skipped), ink colour 15,
  the ACCENT ("EVER") in colour 14;
- the lines under it (one tile, repeated): colour 13 at rows 2-3, colour 14 at rows 5 and 7;
- the firmware version's characters (VERSION_CHARS) in colour 14, which the app sets green
  or red in the accent palette;
- the sync screen's progress bar: a filled cell (colour 14, rows 1-6) and an empty one (a thin
  colour 13 line at rows 3-4);

Standard library only. usage: python3 -I art.py FONT_BIN OUT_BIN OUT_H
"""

import sys
from pathlib import Path

TITLE = "SYNC FOREVER"
ACCENT = "EVER"
VERSION_CHARS = "0123456789v."
FIRST_CHAR = 32  # font.bin starts at the space


def glyph(font: bytes, ch: str) -> list[list[bool]]:
    t = font[(ord(ch) - FIRST_CHAR) * 32 : (ord(ch) - FIRST_CHAR + 1) * 32]
    return [[bool((t[y * 4 + x // 2] >> (4 if x % 2 == 0 else 0)) & 15) for x in range(8)] for y in range(8)]


def tile(pixels) -> bytes:
    """8x8 colour indices -> 32 bytes, two pixels per byte, left pixel in the high nibble."""
    return bytes((pixels[y][x] << 4) | pixels[y][x + 1] for y in range(8) for x in range(0, 8, 2))


def build(font: bytes) -> tuple[bytes, str]:
    out = bytearray()
    letters = TITLE.replace(" ", "")
    accent_from = len(letters) - len(ACCENT)
    for i, ch in enumerate(letters):
        ink = 14 if i >= accent_from else 15
        g = glyph(font, ch)
        big = [[ink if g[y // 2][x // 2] else 0 for x in range(16)] for y in range(16)]
        for ty in (0, 8):
            for tx in (0, 8):
                out += tile([line[tx : tx + 8] for line in big[ty : ty + 8]])
    lines = len(out) // 32
    rows = {2: 13, 3: 13, 5: 14, 7: 14}
    out += tile([[rows.get(y, 0)] * 8 for y in range(8)])
    version = len(out) // 32
    for ch in VERSION_CHARS:
        g = glyph(font, ch)
        out += tile([[14 if g[y][x] else 0 for x in range(8)] for y in range(8)])
    bar = len(out) // 32
    out += tile([[14 if 1 <= y <= 6 else 0] * 8 for y in range(8)])
    out += tile([[13 if 3 <= y <= 4 else 0] * 8 for y in range(8)])
    header = f"""/* Generated by tools/art.py from the font: tile numbers relative to ART_TILE. */
#ifndef ART_H
#define ART_H
#define ART_TITLE "{TITLE}"
#define ART_TITLE_TILES 0 /* 4 per letter, spaces skipped: TL TR BL BR */
#define ART_LINES {lines}
#define ART_VERSION {version} /* "{VERSION_CHARS}" in colour 14: digits, then v, then . */
#define ART_BAR_FULL {bar} /* the progress bar's cells (palette 0) */
#define ART_BAR_EMPTY {bar + 1}
#define ART_TILES {len(out) // 32}
#endif
"""
    return bytes(out), header


def main() -> int:
    font, out_bin, out_h = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    data, header = build(font.read_bytes())
    out_bin.write_bytes(data)
    out_h.write_text(header)
    return 0


if __name__ == "__main__":
    sys.exit(main())
